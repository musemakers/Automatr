export function slugify(name) {
  const s = String(name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);
  return s.length >= 2 ? s : `customer-${Date.now().toString(36)}`;
}

export async function uniqueSlug(base) {
  let slug = slugify(base);
  if (!SLUG_RE.test(slug)) slug = `c-${slug}`.slice(0, 48);
  let candidate = slug;
  for (let i = 2; await Customer.exists({ slug: candidate }); i += 1) candidate = `${slug.slice(0, 44)}-${i}`;
  return candidate;
}

/**
 * Creates a customer and its storage folder (<upload root>/customers/<slug>/ plus the
 * delivery subfolder). The folder name is fixed here and never changes afterwards.
 */
export async function createCustomer({ name, slug, industry, country, notes, limits, plan, features }) {
  const finalSlug = slug ? String(slug).toLowerCase() : await uniqueSlug(name);
  if (!SLUG_RE.test(finalSlug)) throw Object.assign(new Error('Folder/slug must be 2-48 chars: lowercase letters, numbers and dashes.'), { status: 400 });
  if (await Customer.exists({ slug: finalSlug })) throw Object.assign(new Error(`A customer with the folder name "${finalSlug}" already exists.`), { status: 409 });
  const customer = await Customer.create({
    name: String(name).trim(),
    slug: finalSlug,
    industry: industry || 'Technology',
    country: String(country || '').trim().slice(0, 80),
    notes: notes || '',
    plan: plan === 'one_time' ? { type: 'one_time', startsAt: new Date() } : { type: 'monthly', startsAt: null },
    storage: { folder: finalSlug },
    features: { billboards: Boolean(features?.billboards), multiSceneVideo: Boolean(features?.multiSceneVideo), preciseFontText: Boolean(features?.preciseFontText), designOptions: cleanDesignOptions(features?.designOptions) },
    limits: {
      imagesPerMonth: limits?.imagesPerMonth ?? null,
      videosPerMonth: limits?.videosPerMonth ?? null,
      imageGenerationsPerMonth: limits?.imageGenerationsPerMonth ?? null,
      videoGenerationsPerMonth: limits?.videoGenerationsPerMonth ?? null
    }
  });
  ensureCustomerFolders(customer);
  return customer;
}

export function ensureCustomerFolders(customer) {
  const base = uploadDir({ customer });
  fs.mkdirSync(path.join(base, customer.delivery?.subfolder || 'delivered'), { recursive: true });
  return base;
}

/** What the client needs to know about who is logged in and which workspace they're in. */
export async function sessionPayload(user, customer) {
  let customers = [];
  if (user.role === 'admin') {
    customers = (await Customer.find({ status: { $ne: 'archived' } }).sort({ name: 1 })).map((c) => c.toSummary());
  } else if (customer) {
    customers = [customer.toSummary()];
  }
  return {
    user: user.toSafeJSON(customer || undefined),
    customer: customer ? customer.toPublicJSON() : null,
    customers,
    // An agency admin looking at a customer's workspace can view and manage settings but cannot create creatives there.
    viewOnly: user.role === 'admin' && Boolean(customer) && String(customer._id) !== String(user.customer || '')
  };
}

/**
 * The customer's current monthly cycle: it starts on the day-of-month the customer was created
 * (UTC midnight; a 31st-created customer rolls on the last day of shorter months) and lasts until
 * the same day next month.
 */
export function billingCycle(createdAt, now = new Date()) {
  const anchor = new Date(createdAt || now).getUTCDate();
  const startOf = (y, m) => new Date(Date.UTC(y, m, Math.min(anchor, new Date(Date.UTC(y, m + 1, 0)).getUTCDate())));
  let y = now.getUTCFullYear();
  let m = now.getUTCMonth();
  let start = startOf(y, m);
  if (now < start) {
    m -= 1;
    if (m < 0) { m = 11; y -= 1; }
    start = startOf(y, m);
  }
  let ny = y;
  let nm = m + 1;
  if (nm > 11) { nm = 0; ny += 1; }
  return { start, end: startOf(ny, nm) };
}

/** Real (non-placeholder) images and videos generated by this customer's own people this cycle. */
const ONE_TIME_END = new Date('9999-12-31T00:00:00Z'); // a one-time package has no end date

/**
 * The period the customer's limits apply to: the current month for a Monthly plan, or everything since the package
 * started for a One-time package (which never renews).
 */
export function customerCycle(customer, now = new Date()) {
  if (customer?.plan?.type === 'one_time') return { start: customer.plan.startsAt || customer.createdAt || now, end: ONE_TIME_END, oneTime: true };
  return { ...billingCycle(customer?.createdAt, now), oneTime: false };
}

/** `cards: true` also counts the customer-facing generations (a heavier read, used by the admin screens only, not on every generate call). */
export async function generationUsage(customer, { cards = false } = {}) {
  const cycle = customerCycle(customer);
  const agencyIds = await User.find({ role: 'admin' }).distinct('_id');
  const cardCounts = cards ? await countCustomerGenerations(customer._id, cycle, agencyIds) : { image: null, video: null };
  const rows = await unscoped(async () =>
    await AiUsageLog.aggregate([
      {
        $match: {
          customer: new mongoose.Types.ObjectId(String(customer._id)),
          type: { $in: ['image', 'video'] },
          provider: { $ne: 'placeholder' },
          createdAt: { $gte: cycle.start, $lt: cycle.end },
          user: { $nin: agencyIds }
        }
      },
      { $group: { _id: '$type', n: { $sum: 1 } } }
    ])
  );
  const n = (t) => rows.find((r) => r._id === t)?.n || 0;
  // Superadmin top-ups granted during this cycle add to the monthly limit. They mean nothing
  // for an unlimited (null) allowance.
  const topUp = (kind) =>
    (customer.topUps || []).filter((t) => t.kind === kind && t.at >= cycle.start && t.at < cycle.end).reduce((sum, t) => sum + t.amount, 0);
  const meter = (kind, base) => {
    const extra = base === null || base === undefined ? 0 : topUp(kind);
    return { used: n(kind), limit: base === null || base === undefined ? null : base + extra, baseLimit: base ?? null, topUp: extra };
  };
  return {
    plan: cycle.oneTime ? 'one_time' : 'monthly',
    cycleStart: cycle.start,
    cycleEnd: cycle.oneTime ? null : cycle.end, // null = one-time package, no renewal date
    images: meter('image', customer.limits?.imagesPerMonth),
    videos: meter('video', customer.limits?.videosPerMonth),
    // The customer-facing figures (completed cards on the Usage page) next to the AI ones above, so both can be seen together.
    customerGenerations: {
      images: { used: cardCounts.image, limit: customer.limits?.imageGenerationsPerMonth ?? null },
      videos: { used: cardCounts.video, limit: customer.limits?.videoGenerationsPerMonth ?? null }
    }
  };
}

const monthStart = () => {
  const d = new Date();
  return new Date(d.getFullYear(), d.getMonth(), 1);
};

/** Estimated AI spend (USD) for one customer this calendar month. */
export async function monthSpendUsd(customerId) {
  const rows = await unscoped(async () =>
    await AiUsageLog.aggregate([
      { $match: { customer: new mongoose.Types.ObjectId(String(customerId)), createdAt: { $gte: monthStart() } } },
      { $group: { _id: null, total: { $sum: '$estimatedCostUsd' } } }
    ])
  );
  return rows[0]?.total || 0;
}

/** Per-customer usage roll-up for the agency admin (all-time + this month). */
export async function usageByCustomer() {
  const since = monthStart();
  const rows = await unscoped(async () =>
    await AiUsageLog.aggregate([
      {
        $group: {
          _id: '$customer',
          totalCalls: { $sum: 1 },
          totalCostUsd: { $sum: '$estimatedCostUsd' },
          monthCostUsd: { $sum: { $cond: [{ $gte: ['$createdAt', since] }, '$estimatedCostUsd', 0] } },
          imageCalls: { $sum: { $cond: [{ $eq: ['$type', 'image'] }, 1, 0] } },
          videoCalls: { $sum: { $cond: [{ $eq: ['$type', 'video'] }, 1, 0] } },
          textCalls: { $sum: { $cond: [{ $eq: ['$type', 'text'] }, 1, 0] } },
          lastActivityAt: { $max: '$createdAt' }
        }
      }
    ])
  );
  const customers = await Customer.find({}).sort({ name: 1 });
  const byId = new Map(rows.map((r) => [String(r._id), r]));
  return customers.map((c) => {
    const r = byId.get(String(c._id)) || {};
    return {
      customer: c.toSummary(),
      budget: c.budget,
      totalCalls: r.totalCalls || 0,
      totalCostUsd: r.totalCostUsd || 0,
      monthCostUsd: r.monthCostUsd || 0,
      textCalls: r.textCalls || 0,
      imageCalls: r.imageCalls || 0,
      videoCalls: r.videoCalls || 0,
      lastActivityAt: r.lastActivityAt || null
    };
  });
}
